"""生成「其余年级」知识点 INSERT SQL（幂等，不调用任何 AI / 不自动写库）。

覆盖：小学 G1-G6 + 初中 G8/G9（按真实课标对齐学科）。
用法：
    python tools/gen_kp_sql.py
输出：
    output/knowledge_points_insert.sql   （INSERT IGNORE，重复 (subject,grade,unit,title) 自动跳过）

内容由人工按课标编写（详细/复杂版），交付后由用户在线上库手动执行。
"""
from __future__ import annotations
import os
from datetime import datetime

# 课程大纲 + 知识点（由下方数据块填充）。
# 结构：CURRICULUM[grade][subject] = [(unit, [kp, ...]), ...]
#   kp = {"title":..., "summary":..., "content":..., "examples":..., "difficulty":int}
CURRICULUM: dict = {}


def esc(s: str) -> str:
    s = str(s)
    s = s.replace("\\", "\\\\").replace("'", "\\'")
    s = s.replace("\n", " ").replace("\r", " ")
    return s


def build_sql() -> str:
    lines = [
        "-- 其余年级知识点批量插入（幂等 INSERT IGNORE；重复 subject+grade+unit+title 自动跳过）",
        f"-- 生成时间: {datetime.now().isoformat(timespec='seconds')}",
        "-- 覆盖: 小学 G1-G6 + 初中 G8/G9（按真实课标对齐学科）",
        "-- 来源标记 source='manual'；在线上库(115.29.213.131/schoolexam)执行本文件即可。",
        "SET NAMES utf8mb4;",
        "",
    ]
    cnt = 0
    for grade in sorted(CURRICULUM):
        for subject, units in CURRICULUM[grade].items():
            for unit, kps in units:
                for kp in kps:
                    title = esc(kp["title"])
                    summary = esc(kp.get("summary", ""))
                    content = esc(kp.get("content", ""))
                    examples = esc(kp.get("examples", ""))
                    diff = int(kp.get("difficulty", 2))
                    lines.append(
                        "INSERT IGNORE INTO knowledge_points "
                        "(subject,grade,unit,title,summary,content,examples,difficulty,source) VALUES ("
                        f"'{esc(subject)}',{grade},'{esc(unit)}','{title}','{summary}',"
                        f"'{content}','{examples}',{diff},'manual');"
                    )
                    cnt += 1
    lines.append("")
    lines.append(f"-- 合计 {cnt} 条知识点")
    return "\n".join(lines) + "\n"


def main():
    out_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "output")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "knowledge_points_insert.sql")
    sql = build_sql()
    with open(path, "w", encoding="utf-8") as f:
        f.write(sql)
    print(f"生成 {sql.count('INSERT IGNORE')} 条知识点 SQL -> {path}")


